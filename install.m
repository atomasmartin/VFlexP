function install()
%INSTALL Add VFlexP folders (core, ui, functions, Simulink libraries, MATPOWER-FUBM) to MATLAB path.

repoRoot = fileparts(mfilename('fullpath'));

relDirs = { ...
    '', ...
    'core', ...
    'ui', ...
    'functions', ...
    fullfile('functions', 'masks'), ...
    'tools', ...
    'docs', ...
    'Simulink', ...
    fullfile('Simulink', 'lib'), ...
    fullfile('Simulink', 'lib', 'generators'), ...
    fullfile('Simulink', 'lib', 'converters'), ...
    fullfile('Simulink', 'lib', 'grid'), ...
    fullfile('Simulink', 'lib', 'controls'), ...
    fullfile('MATPOWER-FUBM', 'lib'), ...
    fullfile('MATPOWER-FUBM', 'mips', 'lib'), ...
    fullfile('MATPOWER-FUBM', 'most', 'lib'), ...
    fullfile('MATPOWER-FUBM', 'mp-opt-model', 'lib') ...
};

for k = 1:numel(relDirs)
    p = fullfile(repoRoot, relDirs{k});
    if isfolder(p)
        addpath(p);
    end
end

try
    status = savepath;
    if status == 0
        fprintf('VFlexP paths added and saved successfully.\n');
    else
        fprintf('VFlexP paths added to current MATLAB session (savepath lacked write permission).\n');
    end
catch
    fprintf('VFlexP paths added to current MATLAB session.\n');
end
end
